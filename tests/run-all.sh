#!/bin/bash
# tests/run-all.sh [pkg ...] -- run the device acceptance suite and emit
# tests/REPORT.md (gitignored: it is output, not source).
#
# Exit code: 0 no FAIL, 1 at least one FAIL, 2 device unreachable (all SKIP).
set -uo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
cd "$here"
IPAD_HOST="${IPAD_HOST:-ipad}"

pkgs=("$@")
if [ "${#pkgs[@]}" = 0 ]; then
    pkgs=($(ls *.sh 2>/dev/null | grep -vE '^(lib|run-all)\.sh$' | sed 's/\.sh$//'))
fi

dev_up=no
ssh -o BatchMode=yes -o ConnectTimeout=8 "$IPAD_HOST" true 2>/dev/null && dev_up=yes

: > .results
overall=0
for p in "${pkgs[@]}"; do
    start=$(date +%s)
    bash "$p.sh" >> .results 2>&1
    rc=$?
    dur=$(( $(date +%s) - start ))
    echo "STATUS $p rc=$rc dur=${dur}s" >> .results
    [ "$rc" = 1 ] && overall=1
done

# ------------------------------------------------------------- report ----
{
    echo "# Device acceptance report"
    echo
    echo "- host: \`$IPAD_HOST\` (reachable: $dev_up)"
    echo "- run:  \`$(date -u '+%FT%TZ')\`"
    echo "- pkgs: ${#pkgs[@]}"
    echo
    echo "| package | result | pass | fail | skip | time |"
    echo "|---|---|---|---|---|---|"
    for p in "${pkgs[@]}"; do
        line=$(grep -E "^== $p: " .results | tail -1)
        st=$(grep -E "^STATUS $p " .results | tail -1)
        pas=$(printf '%s' "$line" | sed -n 's/.*pass=\([0-9]*\).*/\1/p')
        fai=$(printf '%s' "$line" | sed -n 's/.*fail=\([0-9]*\).*/\1/p')
        ski=$(printf '%s' "$line" | sed -n 's/.*skip=\([0-9]*\).*/\1/p')
        dur=$(printf '%s' "$st" | sed -n 's/.*dur=\([0-9]*\)s.*/\1/p')
        [ -n "$fai" ] && [ "$fai" -gt 0 ] && res="**FAIL**" || res="ok"
        [ "$pas" = "0" ] && [ "$ski" -gt 0 ] 2>/dev/null && res="skip"
        echo "| $p | $res | ${pas:-0} | ${fai:-0} | ${ski:-0} | ${dur:-0}s |"
    done
    echo
    echo "Generated by tests/run-all.sh; add a tests/<pkg>.sh to grow it."
} > REPORT.md

grep -E "^(PASS|FAIL|SKIP|==)" .results
echo
[ "$dev_up" = no ] && overall=2
[ "$overall" = 0 ] && echo "SUITE OK ($(grep -c '^PASS' .results) cases)" \
                  || echo "SUITE rc=$overall (fail=$(grep -c '^FAIL' .results) skip=$(grep -c '^SKIP' .results))"
rm -f .results
exit "$overall"
