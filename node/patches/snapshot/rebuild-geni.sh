#!/bin/bash
# Rebuild geni/{snapshot,embedded}.o from the device mksnapshot v10 dump.
# Usage: rebuild-geni.sh <snapgen_dir_with_snapshot.cc,embedded_code.bin,embedded_data.bin>
set -euo pipefail
NODE_TREE="${NODE_TREE:-$HOME/scratch/node-research/node-v22.23.4}"
N=$NODE_TREE
G=$N/out/Release/obj.target/v8_snapshot/geni
S=${1:?need snapgen dir}
SNAP=$S/snapshot.cc
CODE=$S/embedded_code.bin
DATA=$S/embedded_data.bin
[ -f "$SNAP" ] && [ -f "$CODE" ] && [ -f "$DATA" ] || { echo "missing inputs in $S"; exit 1; }

# 1) embedded.S (byte-exact wrapper, mirrors the v9 layout):
#    .text code blob, .const_data [code_size .long][data_size .long][data blob]
python3 - "$CODE" "$DATA" "$G/embedded.S" <<'PYEOF'
import sys
code = open(sys.argv[1], 'rb').read()
data = open(sys.argv[2], 'rb').read()
out = open(sys.argv[3], 'w')
out.write("// Autogenerated embedded blob for armv7 iOS 10.3.3.\n")
out.write("// Generated from device mksnapshot dump by host-side script.\n")
out.write("// Do not edit.\n\n.text\n.private_extern _v8_Default_embedded_blob_code_\n_v8_Default_embedded_blob_code_:\n")
def emit(buf):
    for i in range(0, len(buf), 12):
        chunk = buf[i:i+12]
        out.write("  .byte " + ",".join("0x%02x" % b for b in chunk) + "\n")
emit(code)
out.write("\n.const_data\n.private_extern _v8_Default_embedded_blob_code_size_\n_v8_Default_embedded_blob_code_size_:\n")
out.write("  .long %d\n\n" % len(code))
out.write(".private_extern _v8_Default_embedded_blob_data_size_\n_v8_Default_embedded_blob_data_size_:\n")
out.write("  .long %d\n\n" % len(data))
out.write(".private_extern _v8_Default_embedded_blob_data_\n_v8_Default_embedded_blob_data_:\n")
emit(data)
out.close()
print("embedded.S:", len(code), "code bytes,", len(data), "data bytes")
PYEOF

# 2) snapshot.cc wrapper (mirrors the v9 wrapper structure):
python3 - "$SNAP" "$G/snapshot.cc" <<'PYEOF'
import sys
data = open(sys.argv[1], 'rb').read()
out = open(sys.argv[2], 'w')
out.write("// Autogenerated snapshot file. Do not edit.\n\n")
out.write('#include "src/init/v8.h"\n')
out.write('#include "src/base/platform/platform.h"\n\n')
out.write('#include "src/flags/flags.h"\n')
out.write('#include "src/snapshot/snapshot.h"\n\n')
out.write("namespace v8 {\nnamespace internal {\n\n")
out.write("alignas(kPointerAlignment) static const uint8_t blob_data[] = {\n")
for i in range(0, len(data), 15):
    chunk = data[i:i+15]
    out.write(",".join(str(b) for b in chunk))
    out.write(",\n")
out.write("};\n")
out.write("static const int blob_size = %d;\n" % len(data))
out.write("static const v8::StartupData blob =\n{ (const char*) blob_data, blob_size };\n\n")
out.write("const v8::StartupData* Snapshot::DefaultSnapshotBlob() {\n  return &blob;\n}\n\n")
out.write("bool Snapshot::ShouldVerifyChecksum(const v8::StartupData* data) {\n  return v8_flags.verify_snapshot_checksum;\n}\n")
out.write("}  // namespace internal\n}  // namespace v8\n")
out.close()
print("snapshot wrapper:", len(data), "bytes")
PYEOF

# 3) compile both objects with the target toolset flags from v8_snapshot.target.mk
W="$HOME/ios-tool/cxx-wrapper.sh"
INC="-I $N/deps/v8 -I $N/deps/v8/include -I $N/out/Release/obj/gen/generate-bytecode-output-root -I $N/out/Release/obj/gen"
DEF="-D_GLIBCXX_USE_CXX11_ABI=1 -D_FILE_OFFSET_BITS=64 -DNODE_OPENSSL_CONF_NAME=nodejs_conf -DICU_NO_USER_DATA_OVERRIDE -DV8_GYP_BUILD -DV8_TYPED_ARRAY_MAX_SIZE_IN_HEAP=64 -DNODE_MACOS_KEYCHAIN_DISABLED -DNO_RECVMMSG -D__STDC_FORMAT_MACROS -DOPENSSL_NO_PINSHARED -DV8_TARGET_ARCH_ARM -DV8_HOST_TOOLS_CROSS_BUILD -DCAN_USE_ARMV7_INSTRUCTIONS -DCAN_USE_VFP3_INSTRUCTIONS -DCAN_USE_VFP32DREGS -DV8_HAVE_TARGET_OS -DV8_TARGET_OS_IOS '-DV8_EMBEDDER_STRING=\"-node.57\"' -DENABLE_DISASSEMBLER -DV8_PROMISE_INTERNAL_FIELD_COUNT=1 -DOBJECT_PRINT -DV8_ATOMIC_OBJECT_FIELD_WRITES -DV8_ENABLE_LAZY_SOURCE_POSITIONS -DV8_USE_SIPHASH -DV8_ENABLE_SEEDED_ARRAY_INDEX_HASH -DV8_SHARED_RO_HEAP -DNDEBUG -DV8_WIN64_UNWINDING_INFO -DV8_ENABLE_REGEXP_INTERPRETER_THREADED_DISPATCH -DV8_USE_ZLIB -DV8_ENABLE_SPARKPLUG -DV8_ENABLE_TURBOFAN -DV8_ENABLE_WEBASSEMBLY -DV8_ENABLE_JAVASCRIPT_PROMISE_HOOKS -DV8_ENABLE_CONTINUATION_PRESERVED_EMBEDDER_DATA -DV8_ALLOCATION_FOLDING -DV8_ALLOCATION_SITE_TRACKING -DV8_ADVANCED_BIGINT_ALGORITHMS"
FLG="-pthread -Wno-unused-parameter -O3 -fno-omit-frame-pointer -fno-rtti -fno-exceptions -fno-strict-aliasing -std=gnu++20 -I $HOME/ios-tool/x-libdispatch/include -Wno-invalid-offsetof -Wno-nullability-completeness"
mkdir -p "$G"
echo "CC snapshot wrapper"
eval "$W -c '$G/snapshot.cc' -o '$G/snapshot.o' $INC $DEF $FLG"
echo "AS embedded.S"
eval "$W -c '$G/embedded.S' -o '$G/embedded.o' $INC"
ls -la "$G/snapshot.o" "$G/embedded.o"
echo "DONE geni"
